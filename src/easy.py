    for term in sorted(GLOSSARY, key=len, reverse=True):
        pos = covered.find(term)
        if pos >= 0:
            found.append((pos, term, GLOSSARY[term]))
            covered = covered.replace(term, " " * len(term))   # 같은 길이로 지워서 위치가 밀리지 않게
    return [(t, d) for _, t, d in sorted(found)][:limit]
