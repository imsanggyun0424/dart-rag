def find_terms(text: str, limit: int = 8) -> list[tuple[str, str]]:
    """답변 속에 나온 용어와 설명. 긴 용어가 짧은 용어를 포함하면 짧은 쪽은 그 자리에서 중복 계산하지 않는다."""
